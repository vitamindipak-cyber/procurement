export const ALL_LEGAL_EXCEPTIONS: ExceptionItem[] = [
  ...ACT_PROVISO_EXCEPTIONS,
  ...ACT_NON_OBSTANTE_EXCEPTIONS,
  ...RULES_PROVISO_EXCEPTIONS,
  ...RULES_NON_OBSTANTE_EXCEPTIONS,
];

const normalizeNum = (val: string) =>
  val.replace(/[०-९]/g, (digit) => String('०१२३४५६७८९'.indexOf(digit))).toLowerCase().trim();

export function getProhibitionsForProvision(sectionNo: string, lawType: 'act' | 'rules'): ProhibitionItem[] {
  const cleanNums = (sectionNo.match(/[०-९0-9]+[क-ह]?/g) ?? []).map(normalizeNum);
  if (!cleanNums.length) return [];

  return PROHIBITIONS_DATA.filter((p) => {
    if (lawType === 'act' && p.lawType === 'rules') return false;
    if (lawType === 'rules' && p.lawType === 'act') return false;
    const refNormalized = normalizeNum(p.legalReference);
    return cleanNums.some((num) => {
      const regex = new RegExp(`(?:दफा|नियम|§)\\s*${num}\\b`, 'i');
      return regex.test(refNormalized);
    });
  });
}

export function getExceptionsForProvision(sectionNo: string, lawType: 'act' | 'rules'): ExceptionItem[] {
  const cleanNums = (sectionNo.match(/[०-९0-9]+[क-ह]?/g) ?? []).map(normalizeNum);
  if (!cleanNums.length) return [];

  const candidatePool = lawType === 'act'
    ? [...ACT_PROVISO_EXCEPTIONS, ...ACT_NON_OBSTANTE_EXCEPTIONS]
    : [...RULES_PROVISO_EXCEPTIONS, ...RULES_NON_OBSTANTE_EXCEPTIONS];

  return candidatePool.filter((exc) => {
    const refNormalized = normalizeNum(`${exc.legalReference} ${exc.subjectOrSection}`);
    return cleanNums.some((num) => {
      const regex = new RegExp(`(?:दफा|नियम|§)\\s*${num}\\b`, 'i');
      return regex.test(refNormalized);
    });
  });
}
